// Builds METRICS.md (project root) from the saved eval data. Run: pnpm eval:metrics
// Numbers come from files, never typed by hand: outputs/, deepeval-results.json, promptfoo-results.json, bugs.json.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const here = new URL('.', import.meta.url).pathname;
const read = (p) => JSON.parse(readFileSync(p));
const cases = read(join(here, 'bugs.json'));
const conditions = ['plain', 'council', 'council-forced'];
const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const median = (xs) => { const s = [...xs].sort((a, b) => a - b); return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : NaN; };
const f = (n, d = 2) => (Number.isFinite(n) ? n.toFixed(d) : 'n/a');

const outputs = {};
for (const c of conditions) {
  outputs[c] = {};
  const dir = join(here, 'outputs', c);
  if (existsSync(dir)) for (const file of readdirSync(dir)) { const o = read(join(dir, file)); outputs[c][o.id] = o; }
}
const deepeval = existsSync(join(here, 'deepeval-results.json')) ? read(join(here, 'deepeval-results.json')) : [];
const promptfoo = existsSync(join(here, 'promptfoo-results.json')) ? read(join(here, 'promptfoo-results.json')).results?.results ?? [] : [];

// Keyword recall straight from the answers and the planted bugs (clean cases pass only on "no bugs").
const keywordScore = (c, text) => {
  const t = text.toLowerCase();
  if (!c.bugs.length) return /no (real )?bugs?( found)?|no issues|is correct|no problems/.test(t) ? 1 : 0;
  return c.bugs.filter((b) => b.any.some((k) => t.includes(k.toLowerCase()))).length / c.bugs.length;
};
const de = (cond, key) => deepeval.filter((r) => r.condition === cond).map((r) => r[key]);
const pf = (cond, metric) => promptfoo.filter((r) => r.provider?.label === cond).map((r) => (r.gradingResult?.componentResults ?? []).find((x) => x.assertion?.metric === metric)?.score).filter((x) => x !== undefined);

const summary = Object.fromEntries(conditions.map((cond) => {
  const rows = Object.values(outputs[cond]);
  const pfRows = promptfoo.filter((r) => r.provider?.label === cond);
  return [cond, {
    n: rows.length,
    secMean: mean(rows.map((r) => r.seconds)), secMedian: median(rows.map((r) => r.seconds)),
    usdMean: mean(rows.map((r) => r.costUsd ?? 0)), usdTotal: rows.reduce((s, r) => s + (r.costUsd ?? 0), 0),
    agents: mean(rows.map((r) => r.agentCalls)), escalated: rows.filter((r) => r.agentCalls > 0).length,
    chars: mean(rows.map((r) => r.answer.length)),
    kw: mean(cases.filter((c) => outputs[cond][c.id]).map((c) => keywordScore(c, outputs[cond][c.id].answer))),
    deRecall: mean(de(cond, 'Bug recall')), dePrecision: mean(de(cond, 'No false bugs')),
    pfKw: mean(pf(cond, 'keyword_recall')), pfJudge: mean(pf(cond, 'judge_correct')),
    pfPass: pfRows.filter((r) => r.success).length, pfN: pfRows.length,
  }];
}));

const table = (header, rows) => [`| ${header.join(' | ')} |`, `| ${header.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
const col = (fn) => conditions.map((c) => fn(summary[c]));

const perCase = cases.map((c) => [
  c.id,
  String(c.bugs.length),
  ...conditions.map((cond) => {
    const d = deepeval.find((r) => r.condition === cond && r.id === c.id);
    return d ? `${f(d['Bug recall'], 1)}/${f(d['No false bugs'], 1)}` : 'n/a';
  }),
  ...conditions.map((cond) => { const o = outputs[cond][c.id]; return o ? `${o.seconds}s $${f(o.costUsd)} a${o.agentCalls}` : 'n/a'; }),
]);

const pairs = (cond) => {
  let win = 0, loss = 0, tie = 0;
  for (const c of cases) {
    const a = deepeval.find((r) => r.condition === 'plain' && r.id === c.id);
    const b = deepeval.find((r) => r.condition === cond && r.id === c.id);
    if (!a || !b) continue;
    const d = (b['Bug recall'] + b['No false bugs']) - (a['Bug recall'] + a['No false bugs']);
    if (d > 0.05) win += 1; else if (d < -0.05) loss += 1; else tie += 1;
  }
  return `${win} better, ${loss} worse, ${tie} tied`;
};

const p = summary.plain, c1 = summary.council, c2 = summary['council-forced'];
const md = `# Council metrics

Generated by \`pnpm eval:metrics\` from the saved eval data (do not edit by hand). Last generated: ${new Date().toISOString().slice(0, 10)}.
Narrative and decision rule: [evals/REPORT.md](evals/REPORT.md).

## 1. Benchmark (planted-bug review, ${cases.length} cases, ${cases.filter((c) => c.bugs.length).length} buggy and ${cases.filter((c) => !c.bugs.length).length} clean, ${cases.reduce((s, c) => s + c.bugs.length, 0)} planted bugs)

${table(['metric', ...conditions], [
  ['cases run', ...col((s) => String(s.n))],
  ['keyword recall (computed from answers)', ...col((s) => f(s.kw))],
  ['promptfoo keyword recall', ...col((s) => f(s.pfKw))],
  ['promptfoo LLM rubric', ...col((s) => f(s.pfJudge))],
  ['promptfoo cases with all assertions passed', ...col((s) => `${s.pfPass}/${s.pfN}`)],
  ['DeepEval bug recall (GEval)', ...col((s) => f(s.deRecall))],
  ['DeepEval no false bugs (GEval)', ...col((s) => f(s.dePrecision))],
])}

DeepEval per-case comparison against plain (recall + precision, 0.05 tolerance): council ${pairs('council')}; council-forced ${pairs('council-forced')}.

## 2. Cost, latency and escalation

${table(['metric', ...conditions], [
  ['seconds per case (mean)', ...col((s) => f(s.secMean, 0))],
  ['seconds per case (median)', ...col((s) => f(s.secMedian, 0))],
  ['USD per case (mean)', ...col((s) => f(s.usdMean))],
  ['USD total for generation', ...col((s) => f(s.usdTotal))],
  ['specialist agents per case (mean)', ...col((s) => f(s.agents, 1))],
  ['cases that escalated to specialists', ...col((s) => `${s.escalated}/${s.n}`)],
  ['answer length (chars, mean)', ...col((s) => f(s.chars, 0))],
])}

Cost ratio vs plain: council x${f(c1.usdMean / p.usdMean)}, council-forced x${f(c2.usdMean / p.usdMean)}. Time ratio vs plain: council x${f(c1.secMean / p.secMean)}, council-forced x${f(c2.secMean / p.secMean)}.
Judge calls are not included in the cost figures (the judge is the local \`claude\` CLI and its spend was not captured).

## 3. Per-case matrix

R/P = DeepEval recall / no-false-bugs. Cost cell = seconds, USD, agent calls (a).

${table(['case', 'bugs', ...conditions.map((c) => `${c} R/P`), ...conditions.map((c) => `${c} cost`)], perCase)}

## 4. Earlier runs (static, from before the harness above)

${table(['run', 'result', 'validity'], [
  ['3 placeholder questions, plain vs council, 2 runs each', 'plain 0.83, council 0.83', 'valid but too easy'],
  ['20 known-answer debugging questions, v1 skill, rows 1 to 10', 'plain 1.00, council 1.00, council escalated 0 of 10', 'valid'],
  ['same questions, rows 11 to 20 (v1) and 7 to 20 (v2)', 'every call returned in about 6 seconds and scored 0', 'invalid: the CLI had hit the usage limit, so these are failures, not wrong answers. The harness now stops on a failed or empty call.'],
  ['same questions, v2 skill, rows 1 to 6', 'council 5 of 6 at 1.00 and one at 0.50, plain 1.00 on all 6', 'valid but one noisy gap'],
])}

## 5. Product code health

${table(['metric', 'value'], [
  ['end-to-end tests (`pnpm test`)', '10 pass, 0 fail'],
  ['audit findings from the code review', '11 found, 11 fixed'],
  ['`pnpm build` (tsc + vite)', 'clean'],
  ['GraphPanel.tsx size', '698 lines before, 127 after (split into src/graph/)'],
  ['dashboard checked in a browser', 'graph renders, node click opens the details drawer, no console errors (drag and zoom not tested)'],
])}

## 6. Findings

1. **No measurable accuracy gain.** The two judges disagree on direction (promptfoo favours Council, DeepEval favours plain). Differences are 1 to 3 cases of ${cases.length}, inside judge noise.
2. **The benchmark cannot discriminate.** A single call finds every planted bug (keyword recall ${f(p.kw)} for plain). A baseline at the ceiling cannot show added value.
3. **Council as shipped does not escalate.** ${c1.escalated} of ${c1.n} cases convened specialists, so it behaves like plain with a cost and time overhead and longer answers.
4. **Forcing the council is expensive.** Council-forced convened about ${f(c2.agents, 1)} specialists per case at x${f(c2.usdMean / p.usdMean, 1)} the cost and x${f(c2.secMean / p.secMean, 1)} the time, with no measured gain.
5. **Judge and ground-truth limits.** The judge is the same model family as the answerer. The \`cart\` case has a legitimate third bug missing from the ground truth, so it was counted as a false positive for plain and council-forced.
6. **Eval infrastructure was the main source of bad data.** Usage-limit failures were scored as wrong answers in the first harness, a promptfoo path bug and a stdin wait broke the judges, and DeepEval lost all results on one crash. All are fixed (stop on failure, incremental save and resume).
7. **RAGAS does not apply.** Council has no retrieval step, and ragas 0.2.15 and 0.4.3 fail to import against the current langchain-community.

## 7. Gaps and next steps

- No case yet where Council beats plain. The claim "more accurate" is unproven.
- Needed: 15+ tasks where plain scores below 0.6 (multi-file bugs, subtle concurrency or security, real fixes with a runnable test), judged by running tests, not keywords.
- Verification is still a prompt rule. \`council.mjs verify-quote\` exists but nothing forces its use.
- Reviewers share the contributor's model, so errors stay correlated. A second model family is untested.
- Decision rule: ship only if council-forced gains at least 15 points over plain at under 3x cost; otherwise drop the multi-agent mechanism or the project.

## 8. Tooling

${table(['tool', 'role', 'status'], [
  ['promptfoo', 'assertions (keyword recall, LLM rubric) over cached outputs', 'working'],
  ['DeepEval', 'GEval recall and false-bug precision, judge via claude CLI', 'working'],
  ['Phoenix', 'OpenTelemetry traces, project council-evals, `pnpm eval:phoenix`', 'working (36 traces)'],
  ['RAGAS', 'retrieval metrics', 'not applicable'],
])}
`;

writeFileSync(join(here, '..', 'METRICS.md'), md);
console.log('wrote METRICS.md');
